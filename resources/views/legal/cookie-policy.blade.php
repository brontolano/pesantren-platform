<h1>Cookie Policy</h1>
<p class="updated">Terakhir diperbarui: 5 Juni 2026</p>

<p>Halaman ini menjelaskan bagaimana Pesantren Platform menggunakan cookie dan teknologi serupa.</p>

<h2>1. Apa Itu Cookie?</h2>
<p>Cookie adalah file teks kecil yang disimpan di perangkat Anda saat mengunjungi website. Cookie membantu website berfungsi dengan baik dan memberikan pengalaman pengguna yang lebih baik.</p>

<h2>2. Cookie yang Kami Gunakan</h2>

<h3>Cookie Esensial (Wajib)</h3>
<p>Cookie ini diperlukan agar Platform dapat berfungsi. Tanpa cookie ini, Anda tidak dapat login atau menggunakan fitur dasar.</p>
<ul>
    <li><strong>Session cookie:</strong> Menjaga sesi login Anda tetap aktif</li>
    <li><strong>CSRF token:</strong> Melindungi dari serangan Cross-Site Request Forgery</li>
    <li><strong>Preferensi cookie:</strong> Menyimpan pilihan cookie Anda</li>
</ul>

<h3>Cookie Fungsional</h3>
<p>Cookie ini membantu mengingat preferensi Anda:</p>
<ul>
    <li><strong>Bahasa:</strong> Menyimpan preferensi bahasa antarmuka</li>
    <li><strong>Tema:</strong> Menyimpan preferensi tampilan (terang/gelap)</li>
</ul>

<h2>3. Cookie Pihak Ketiga</h2>
<p>Saat ini kami <strong>tidak menggunakan</strong> cookie pelacakan, cookie iklan, atau cookie analitik pihak ketiga (seperti Google Analytics). Jika di masa depan kami menambahkan layanan analitik, kebijakan ini akan diperbarui.</p>

<h2>4. Mengelola Cookie</h2>
<p>Anda dapat mengatur cookie melalui pengaturan browser Anda:</p>
<ul>
    <li><strong>Chrome:</strong> Settings &gt; Privacy and Security &gt; Cookies</li>
    <li><strong>Firefox:</strong> Settings &gt; Privacy &amp; Security &gt; Cookies</li>
    <li><strong>Safari:</strong> Preferences &gt; Privacy &gt; Cookies</li>
    <li><strong>Edge:</strong> Settings &gt; Cookies and Site Permissions</li>
</ul>
<p>Menonaktifkan cookie esensial akan membuat Anda tidak dapat menggunakan Platform.</p>

<h2>5. Perubahan</h2>
<p>Kami dapat memperbarui cookie policy ini jika ada perubahan pada cookie yang kami gunakan. Perubahan berlaku sejak dipublikasikan di halaman ini.</p>

